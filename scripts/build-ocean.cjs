const fs=require('node:fs');
const path=require('node:path');
const {stripTypeScriptTypes}=require('node:module');
const root=path.resolve(__dirname,'..');
const names=['math','species','world','renderer'];
const modules=names.map(name=>{
  const file=path.join(root,'vendor/ascii-sharks',name+'.ts');
  let source=fs.readFileSync(file,'utf8');
  // Convert the two upstream constructor parameter properties before erasable-only stripping.
  if(name==='world') source=source.replace(/constructor\(\s*private sharkSpecs: SharkSpec\[\] = DEFAULT_SHARKS,\s*private fishCount\?: number,\s*\) \{\}/, 'constructor(sharkSpecs: SharkSpec[] = DEFAULT_SHARKS, fishCount?: number) { this.sharkSpecs=sharkSpecs; this.fishCount=fishCount; }');
  if(name==='renderer') source=source.replace('constructor(private canvas: HTMLCanvasElement) {', 'constructor(canvas: HTMLCanvasElement) { this.canvas=canvas;');
  return stripTypeScriptTypes(source,{mode:'strip'})
    .replace(/^import\s[\s\S]*?;\s*/gm,'')
    .replace(/^export\s+(?=(?:const|let|class|function)\b)/gm,'');
});
const header='/* ASCII sharks by stackedlol: https://github.com/stackedlol/ascii-sharks\n * Upstream c521e24a787e6d4cc460d4cf2b9815f25e4fe453; see vendor/ascii-sharks/UPSTREAM.md.\n * Generated by node scripts/build-ocean.cjs; edit the controller/source, not this bundle. */\n';
const controller=['ocean-controller.js','foreground-controller.js'].map(name=>fs.readFileSync(path.join(root,'src',name),'utf8')).join('\n');
const output=header+'(() => {\n'+modules.join('\n')+'\n'+controller+'\n})();\n';
new(require('node:vm').Script)(output);
fs.writeFileSync(path.join(root,'docs/ocean.js'),output);console.log('Built original ASCII shark renderer and lifecycle adapter');
